 # input and feedback of the left half
 [('R17','2'),J(40,32)],[J(40,32),('R18','1')],[J(40,32),J(51,32)],[('R18','2'),('C4','1')],[('C4','2'),('V3','1')],
 [('V3','2'),g3],
 # differential pair; crossed collectors: Q2 → R6 (right half), Q3 → R16 (left)
