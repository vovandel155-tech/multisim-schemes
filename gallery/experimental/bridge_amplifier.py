# EXPERIMENTAL, does not work in Multisim yet. Bridge (BTL) power amplifier from an LTspice drawing: 19.5 V supply, 8 Ohm speaker between the two outputs.
# Differential pair Q2, Q3 (2N3904, tail R9) with dividers R19/R20 and R22/R21; input V3 (1 kHz sine) through C4, R18 to the Q2 base;
# feedback: output L — R17 to the Q2 base, output R — R10 to the Q3 base. Crossed collectors: Q3 → R16 → VAS of the left half
# (Q4, 2N3906, compensation C3), Q2 → R6 → VAS of the right half (Q1, C1). Output stages — Darlington TIP121/TIP127 (Q9/Q10, Q11/Q12),
# bias — D2/D1 (1N4148, N=4), emitter resistors R12, R13 / R2, R3 of 0.4 Ohm, current limiting Q7, Q8 / Q5, Q6.
# Placement and wiring as in the drawing; «+V» — VCC symbol 19.5 V, common ground — a bus at the bottom.
# Multimeter XMM1 on the speaker (AC mode — rms voltage, DC mode — output offset).
S=Scheme('bridge_amplifier',outdir=GALLERY)
P=S.part
def R(n,x,y,v,rot=0): P(n,'R','1',x,y,rot=rot,value=v)
# --- left half ---
P('Q9','TIP121','C',11,2,mirror=True)                     # C (11,2), B (14,6), E (11,10)
P('Q7','Q3904','C',22,9)                                  # C (22,9), B (19,13), E (22,17)
R('R12',11,16,'0.4'); R('R13',11,25,'0.4')
P('Q8','P3906','E',22,28,rot=180,mirror=True)             # E (22,28), B (19,32), C (22,36)
P('Q10','TIP127','E',11,35,rot=180)                       # E (11,35), B (14,39), C (11,43)
R('R14',27,3,'500')
P('Q4','P3906','E',27,10,rot=180)                         # E (27,10), B (30,14), C (27,18)
P('C3','C','1',32,20,rot=270,value='200p')                # 1 (32,20), 2 (37,20)
P('D2','D4148x4','A',27,24,rot=180,mirror=True)           # A (27,24), K (27,30)
R('R15',27,40,'3k'); R('R16',44,14,'10k',rot=270)          # R16: 1 (44,14), 2 (49,14)
R('R17',40,25,'200k'); R('R18',40,34,'10k')
P('C4','C','1',40,41,value='0.33u')                       # 1 (40,41), 2 (40,46)
P('V3','VSIN','1',40,60,value='0.1'); g3=S.gnd(40,67)     # 1 (+) (40,60), 2 (40,65)
# --- differential pair ---
R('R19',51,20,'50k'); R('R20',51,38,'50k')
R('R7',57,3,'5k'); R('R8',66,3,'5k')
P('Q2','Q3904','C',57,28)                                 # C (57,28), B (54,32), E (57,36)
P('Q3','Q3904','C',66,28,mirror=True)                     # C (66,28), B (69,32), E (66,36)
R('R9',61,42,'10k')
R('R22',74,20,'50k'); R('R21',74,38,'50k')
R('R10',82,25,'200k'); R('R11',82,34,'10k')
P('C2','C','1',82,41,value='0.33u')
R('R6',77,12,'10k',rot=270)                               # 1 (77,12), 2 (82,12)
# --- right half ---
R('R4',91,1,'500')
P('Q1','P3906','E',91,8,rot=180,mirror=True)              # E (91,8), B (88,12), C (91,16)
P('C1','C','1',85,18,rot=270,value='200p')                # 1 (85,18), 2 (90,18)
P('D1','D4148x4','A',91,24,rot=180,mirror=True)           # A (91,24), K (91,30)
R('R5',91,40,'3k')
P('Q5','Q3904','C',101,9,mirror=True)                     # C (101,9), B (104,13), E (101,17)
P('Q11','TIP121','C',111,2)                               # C (111,2), B (108,6), E (111,10)
R('R2',111,16,'0.4'); R('R3',111,25,'0.4')
P('Q6','P3906','E',101,28,rot=180)                        # E (101,28), B (104,32), C (101,36)
P('Q12','TIP127','E',111,35,rot=180,mirror=True)          # E (111,35), B (108,39), C (111,43)
# --- supply, ground, speaker, multimeter ---
vcc=S.vcc(116,0,volts=19.5); g=S.gnd(116,50)
R('RL',61,58,'8',rot=270)                                  # speaker: 1 (61,58), 2 (66,58)
P('XMM1','XMM','1',61,75)                                 # «+» (61,75) — output L, «−» (63,75) — output R
